//! ArgoCD Application + AppProject templates (F-7).
//! Template ArgoCD Application + AppProject (F-7).
//!
//! The generator previously detected an ArgoCD project (marker
//! `argocd/application.yaml`) and then failed with "unknown template", so the
//! only way to get a working manifest was to write it by hand. These templates
//! emit the standard pair under `.argocd/`: an `AppProject` that scopes the
//! repositories and namespaces, and an `Application` that syncs the project's
//! manifests into that project.
//! (Trước đây generator nhận diện project ArgoCD qua marker
//! `argocd/application.yaml` rồi fail "unknown template", nên chỉ viết tay mới
//! có manifest chạy được. Template này sinh cặp chuẩn dưới `.argocd/`:
//! `AppProject` giới hạn repo/namespace và `Application` sync manifest của
//! project vào đó.)

/// `AppProject` scoping repositories, destinations and resources.
/// `AppProject` giới hạn repo, destination và resource.
pub const ARGOCD_PROJECT_TEMPLATE: &str = r#"apiVersion: argoproj.io/v1alpha1
kind: AppProject
metadata:
  name: {name}
  namespace: argocd
  finalizers:
    - resources-finalizer.argocd.argoproj.io
spec:
  description: "{name} (generated by mgc ci-generate)"
  sourceRepos:
    - '*'
  destinations:
    - namespace: '{name}'
      server: https://kubernetes.default.svc
  clusterResourceWhitelist:
    - group: ''
      kind: Namespace
  namespaceResourceBlacklist:
    - group: ''
      kind: ResourceQuota
    - group: ''
      kind: LimitRange
"#;

/// `Application` that syncs the project into its own namespace.
/// `Application` sync project vào namespace riêng.
pub const ARGOCD_APPLICATION_TEMPLATE: &str = r#"apiVersion: argoproj.io/v1alpha1
kind: Application
metadata:
  name: {name}
  namespace: argocd
  finalizers:
    - resources-finalizer.argocd.argoproj.io
spec:
  project: {name}
  source:
    repoURL: '{repo_url}'
    targetRevision: {tag}
    path: deploy
  destination:
    server: https://kubernetes.default.svc
    namespace: '{name}'
  syncPolicy:
    automated:
      prune: true
      selfHeal: true
    syncOptions:
      - CreateNamespace=true
"#;
