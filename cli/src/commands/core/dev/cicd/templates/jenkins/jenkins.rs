//! Jenkins declarative `Jenkinsfile` template.
//! Template `Jenkinsfile` khai báo (declarative) cho Jenkins.
//!
//! Same supply-chain contract as the other generated pipelines: the installer is
//! fetched from an immutable commit SHA into a file (never piped straight into a
//! shell) and its digest is verified before execution.
//! (Cùng hợp đồng supply-chain như các pipeline khác: installer tải từ commit
//! SHA bất biến ra file, không pipe thẳng vào shell, và verify digest trước khi
//! chạy.)
pub(in crate::commands::core::dev::cicd) const JENKINS_TEMPLATE: &str = r#"// Generated by `mgc ci-generate`. Regenerate instead of editing by hand.
// Sinh bởi `mgc ci-generate`. Hãy sinh lại thay vì sửa tay.
pipeline {
    // `label` keeps the agent choice with the operator: a Jenkins deployment
    // decides which node images exist, so pinning an image here would fail on
    // controllers that do not provide it.
    // (`label` để operator chọn agent: mỗi Jenkins deployment có image riêng,
    // ghim image ở đây sẽ hỏng trên controller không có image đó.)
    agent { label 'rust' }

    stages {
        stage('Setup MagiCore {tag}') {
            steps {
                sh '''#!/bin/sh
                    set -eu
                    pin_dir="$(mktemp -d)"
                    trap 'rm -rf "$pin_dir"' EXIT
                    installer="$pin_dir/install-from-gh.sh"
                    curl -fsSL "https://raw.githubusercontent.com/mingd-153/MagiCore/{installer_sha}/scripts/install-from-gh.sh" -o "$installer"
                    if curl -fsSL "https://raw.githubusercontent.com/mingd-153/MagiCore/{installer_sha}/scripts/install-from-gh.sh.sha256" -o "$pin_dir/install-from-gh.sh.sha256"; then
                      (cd "$pin_dir" && { sha256sum -c install-from-gh.sh.sha256 || shasum -a 256 -c install-from-gh.sh.sha256; })
                    else
                      echo "WARNING: no .sha256 checksum file published next to the installer — companion verification skipped"
                    fi
                    if [ -n "{installer_sha256}" ]; then
                      echo "{installer_sha256}  $installer" | { sha256sum -c - || shasum -a 256 -c -; }
                    else
                      echo "WARNING: installer integrity NOT pinned (MGC_INSTALLER_SHA256 empty) — trusting commit SHA {installer_sha} only"
                    fi
                    bash "$installer" --version {tag}
                    mgc --version
                '''
            }
        }
        stage('Install') {
            steps {
                sh 'mgc install'
            }
        }
        stage('Verify') {
            steps {
                sh 'MGC_AUDIT_STRICT=1 mgc verify'
            }
        }
    }

    post {
        always {
            cleanWs()
        }
    }
}
"#;
