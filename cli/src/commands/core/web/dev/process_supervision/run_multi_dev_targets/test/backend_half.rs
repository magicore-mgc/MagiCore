//! Backend-half startup with a trivial Python fixture.
//! Khởi động nửa backend với fixture Python tối giản.
//!
//! The fixture prints a ready line and exits after a moment, so the dev lane's
//! backend path is exercised end to end — resolver, launch, guard, cancellation —
//! without a toolchain, a network call or a package manager.
//! Fixture in dòng ready rồi thoát sau một nhịp, nên đường backend của lane dev
//! được chạy trọn — resolver, launch, guard, hủy — mà không cần toolchain, mạng
//! hay package manager.

use std::time::Duration;

use super::super::{BACKEND_ROLE, build_backend_launch, readiness_line, run_dev_launch_with_guard};
use crate::commands::compat::CompatMode;
use crate::commands::core::dev_port::PORT_WEB_BE;
use crate::commands::core::web::implementation::DevTarget;

/// Fixture entrypoint the server fixture is generated as.
/// Entrypoint fixture mà server fixture được sinh thành.
const SERVER_FIXTURE: &str = "main.py";

/// Trivial backend that prints a ready line and stops.
/// Backend tối giản in dòng ready rồi dừng.
///
/// It binds nothing, so the test never touches a port; it still exits non-zero
/// on timeouts so a hang is a failure rather than a slow pass.
/// Nó không bind gì nên test không chạm port; vẫn thoát khác 0 khi hết giờ để
/// treo là lỗi chứ không phải pass chậm.
const READY_SERVER: &str = r#"# Fixture server generated by the dev backend-half test.
# Server fixture do test nửa backend của dev sinh ra.
import sys

print("fixture backend ready", flush=True)
sys.exit(0)
"#;

#[test]
fn backend_half_launches_and_reaches_its_ready_line() {
    let project = tempfile::tempdir().expect("project dir");
    let server = project.path().join("server");
    std::fs::create_dir_all(&server).expect("server dir");
    std::fs::write(server.join(SERVER_FIXTURE), READY_SERVER).expect("fixture entrypoint");
    std::fs::write(
        server.join("pyproject.toml"),
        "[project]\nname = \"api-server\"\n",
    )
    .expect("fixture manifest");

    let target = DevTarget {
        dir: server.clone(),
        role: BACKEND_ROLE,
        script_name: "dev",
        host: None,
        port: Some(PORT_WEB_BE),
    };
    let launch = build_backend_launch(&server, &CompatMode::Native, None)
        .expect("the fixture half resolves a launch");
    assert!(launch.program.to_string_lossy().starts_with("python"));

    // No cancel flag: the fixture exits by itself, and the guard must still
    // report the launch as successful.
    // (Không cờ hủy: fixture tự thoát, và guard vẫn phải báo launch thành công.)
    let started = std::time::Instant::now();
    let result = run_dev_launch_with_guard(&target, &launch, &CompatMode::Native, None, None);
    assert!(
        result.is_ok(),
        "fixture backend must start and exit cleanly: {result:?}"
    );
    assert!(
        started.elapsed() < Duration::from_secs(60),
        "the fixture must not wait on a server that never binds"
    );
}

#[test]
fn readiness_line_names_the_backend_origin() {
    assert_eq!(
        readiness_line(BACKEND_ROLE, "127.0.0.1", PORT_WEB_BE),
        format!("[backend] ready on http://127.0.0.1:{PORT_WEB_BE}")
    );
}
