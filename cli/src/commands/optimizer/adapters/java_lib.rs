//! `adapters/java_lib.rs` — Java (JVM) Library Optimizer Adapter
//! Adapter tối ưu thư viện Java (JVM)
//!
//! JVM tuning must reach BOTH build programs: a project may be built by Maven
//! or Gradle, and each reads its own opts variable. Writing only one would leave
//! half the Java projects running with default heap.
//! (Tuning JVM phải tới CẢ hai chương trình build: project có thể do Maven hoặc
//! Gradle build, mỗi bên đọc biến opts riêng. Chỉ ghi một bên sẽ để nửa số
//! project Java chạy heap mặc định.)

use super::OptimizerAdapter;
use crate::commands::optimizer::detect::{HardwareInfo, SystemProfile};
use crate::commands::optimizer::generators::OptimizedConfigFile;
use crate::commands::optimizer::runtime_detect::DetectedRuntime;

/// JVM heap target per machine profile, as a percentage of system memory.
/// (Mục tiêu heap JVM theo profile máy, tính phần trăm RAM hệ thống.)
const HEAP_PERCENT_HIGH: u32 = 75;
const HEAP_PERCENT_STANDARD: u32 = 60;
const HEAP_PERCENT_CONSTRAINED: u32 = 50;

pub struct JavaLibAdapter;

impl OptimizerAdapter for JavaLibAdapter {
    fn name(&self) -> &'static str {
        "Java Library"
    }

    fn matches(&self, runtime: &DetectedRuntime) -> bool {
        matches!(runtime, DetectedRuntime::JvmLib)
    }

    fn generate(&self, hw: &HardwareInfo) -> Vec<OptimizedConfigFile> {
        let heap_percent = match hw.profile {
            SystemProfile::HighPerformance => HEAP_PERCENT_HIGH,
            SystemProfile::Standard => HEAP_PERCENT_STANDARD,
            SystemProfile::Constrained => HEAP_PERCENT_CONSTRAINED,
        };
        let cpu_line = hw
            .cpu_cores
            .map(|cores| format!("-XX:ActiveProcessorCount={cores}"))
            .unwrap_or_default();

        // `MaxRAMPercentage` is relative to the container/system limit, so the
        // same file behaves correctly on a laptop and inside a cgroup.
        // (`MaxRAMPercentage` tính theo giới hạn RAM của container/hệ thống nên
        // cùng một file đúng cả trên laptop và trong cgroup.)
        let opts = format!("-XX:MaxRAMPercentage={heap_percent} -XX:+UseG1GC {cpu_line}",)
            .replace("  ", " ")
            .trim()
            .to_string();

        vec![OptimizedConfigFile {
            relative_path: ".mgc-optimizer/java_lib_runtime.env".to_string(),
            content: format!(
                "# Generated by MagiCore Optimizer for Java (JVM) ({:?})\n\
                 # Applied by both Maven and Gradle so either build program benefits.\n\
                 # (Áp cho cả Maven và Gradle để chương trình build nào cũng hưởng.)\n\
                 MAVEN_OPTS={opts}\n\
                 GRADLE_OPTS={opts}\n\
                 # Keep the daemon out of CI and test runs: a forked daemon hides\n\
                 # exit codes and outlives the command.\n\
                 # (Tắt daemon trong CI/test: daemon ẩn exit code và sống lâu hơn lệnh.)\n\
                 GRADLE_DAEMON=false\n",
                hw.profile
            ),
            description: format!(
                "JVM heap {heap_percent}% of RAM, G1 GC{}",
                hw.cpu_cores
                    .map(|cores| format!(", {cores} processors"))
                    .unwrap_or_default()
            ),
        }]
    }
}
