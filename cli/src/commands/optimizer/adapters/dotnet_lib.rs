//! `adapters/dotnet_lib.rs` — .NET Library Optimizer Adapter
//! Adapter tối ưu thư viện .NET
//!
//! .NET reads tuning from environment variables that both `dotnet build` and
//! `dotnet test` honour, so a project is tuned once for every command.
//! (.NET đọc tuning từ biến môi trường mà cả `dotnet build` và `dotnet test`
//! tôn trọng, nên project được tuning một lần cho mọi lệnh.)

use super::OptimizerAdapter;
use crate::commands::optimizer::detect::{HardwareInfo, SystemProfile};
use crate::commands::optimizer::generators::OptimizedConfigFile;
use crate::commands::optimizer::runtime_detect::DetectedRuntime;

/// Server-GC concurrency per machine profile.
/// (Số heap server-GC đồng thời theo profile máy.)
const HEAP_COUNT_HIGH: u32 = 8;
const HEAP_COUNT_STANDARD: u32 = 4;
const HEAP_COUNT_CONSTRAINED: u32 = 1;

pub struct DotNetLibAdapter;

impl OptimizerAdapter for DotNetLibAdapter {
    fn name(&self) -> &'static str {
        ".NET Library"
    }

    fn matches(&self, runtime: &DetectedRuntime) -> bool {
        matches!(runtime, DetectedRuntime::DotNetLib)
    }

    fn generate(&self, hw: &HardwareInfo) -> Vec<OptimizedConfigFile> {
        let heap_count = match hw.profile {
            SystemProfile::HighPerformance => HEAP_COUNT_HIGH,
            SystemProfile::Standard => HEAP_COUNT_STANDARD,
            SystemProfile::Constrained => HEAP_COUNT_CONSTRAINED,
        };
        let tiered = matches!(
            hw.profile,
            SystemProfile::HighPerformance | SystemProfile::Standard
        );

        vec![OptimizedConfigFile {
            relative_path: ".mgc-optimizer/dotnet_lib_runtime.env".to_string(),
            content: format!(
                "# Generated by MagiCore Optimizer for .NET library ({:?})\n\
                 # Server GC keeps a heap per core; a constrained machine must not\n\
                 # pay that cost, so the count follows the detected profile.\n\
                 # (Server GC giữ một heap mỗi core; máy yếu không nên trả chi phí đó.)\n\
                 DOTNET_gcServer=1\n\
                 DOTNET_GCHeapCount={heap_count}\n\
                 DOTNET_TieredPGO={tiered}\n\
                 # Restore is MagiCore's job; the SDK must not re-run it.\n\
                 # (Restore là việc của MagiCore.)\n\
                 DOTNET_CLI_TELEMETRY_OPTOUT=1\n\
                 DOTNET_NOLOGO=1\n",
                hw.profile
            ),
            description: format!("Server GC on {heap_count} heaps, tiered PGO={tiered}"),
        }]
    }
}
