//! `adapters/swift_lib.rs` — SwiftPM Library Optimizer Adapter
//! Adapter tối ưu thư viện SwiftPM
//!
//! SwiftPM exposes no runtime tuning knob: the compiler owns parallelism and
//! the linker owns strip level. What MagiCore can set is the build-job count and
//! the resolution policy, both of which change wall time on a library build.
//! (SwiftPM không có knob tuning runtime: compiler sở hữu song song, linker sở
//! hữu mức strip. MagiCore đặt được số job build và chính sách resolution —
//! cả hai đổi thời gian build thư viện.)

use super::OptimizerAdapter;
use crate::commands::optimizer::detect::{HardwareInfo, SystemProfile};
use crate::commands::optimizer::generators::OptimizedConfigFile;
use crate::commands::optimizer::runtime_detect::DetectedRuntime;

/// Default build-job count when the CPU count is unknown.
/// (Số job build mặc định khi không biết số CPU.)
const UNKNOWN_CORE_JOBS: usize = 4;

pub struct SwiftLibAdapter;

impl OptimizerAdapter for SwiftLibAdapter {
    fn name(&self) -> &'static str {
        "Swift Library"
    }

    fn matches(&self, runtime: &DetectedRuntime) -> bool {
        matches!(runtime, DetectedRuntime::SwiftLib)
    }

    fn generate(&self, hw: &HardwareInfo) -> Vec<OptimizedConfigFile> {
        // A constrained profile leaves a core for the OS; the others use every
        // core, which is what a clean build wants.
        // (Profile yếu chừa một core cho OS; các profile khác dùng hết core.)
        let jobs = match (hw.cpu_cores, hw.profile) {
            (Some(cores), SystemProfile::Constrained) => cores.saturating_sub(1).max(1),
            (Some(cores), _) => cores.max(1),
            (None, _) => UNKNOWN_CORE_JOBS,
        };

        vec![OptimizedConfigFile {
            relative_path: ".mgc-optimizer/swift_lib_runtime.env".to_string(),
            content: format!(
                "# Generated by MagiCore Optimizer for Swift library ({:?})\n\
                 # MagiCore resolves and installs; SwiftPM must never resolve.\n\
                 # (MagiCore resolve và cài; SwiftPM không được tự resolve.)\n\
                 SWIFTPM_BUILD_JOBS={jobs}\n\
                 SWIFT_BUILD_FLAGS=--disable-automatic-resolution\n",
                hw.profile
            ),
            description: format!("SwiftPM build jobs={jobs}, no automatic resolution"),
        }]
    }
}
