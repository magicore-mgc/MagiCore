//! GPU fact env-file generation for the optimizer.
//! Sinh file env chứa fact GPU cho optimizer.

use crate::commands::optimizer::detect::HardwareInfo;
use crate::commands::optimizer::generators::OptimizedConfigFile;

/// Measured GPU facts as a KEY=value data file; the loader parses it and never evals a shell.
/// (File dữ liệu KEY=value; loader tự parse, không thực thi như shell.)
pub(crate) fn gpu_env_file(hw: &HardwareInfo) -> OptimizedConfigFile {
    fn clean(s: &str) -> String {
        s.chars()
            .map(|c| if c.is_control() { ' ' } else { c })
            .collect()
    }
    let mut content =
        String::from("# Generated by MagiCore Optimizer — measured GPU facts (never guessed)\n");
    match hw.gpu_detection_status {
        crate::commands::optimizer::detect::GpuDetectionStatus::Available => {
            content.push_str(&format!("MGC_GPU_COUNT={}\n", hw.gpus.len()));
        }
        crate::commands::optimizer::detect::GpuDetectionStatus::Partial => {
            content.push_str("# GPU detection partial — observed entries may be incomplete\n");
        }
        crate::commands::optimizer::detect::GpuDetectionStatus::Unavailable => {
            content.push_str("# GPU detection unavailable — no GPU count claim\n");
        }
    }
    for (i, gpu) in hw.gpus.iter().enumerate() {
        content.push_str(&format!("MGC_GPU_{i}_NAME={}\n", clean(&gpu.name)));
        match &gpu.vendor {
            Some(v) => content.push_str(&format!("MGC_GPU_{i}_VENDOR={}\n", clean(v))),
            None => content.push_str(&format!(
                "# MGC_GPU_{i}_VENDOR unset — vendor unrecognized\n"
            )),
        }
        match gpu.vram_mb {
            Some(mb) => content.push_str(&format!("MGC_GPU_{i}_VRAM_MB={mb}\n")),
            None => content.push_str(&format!(
                "# MGC_GPU_{i}_VRAM_MB unset — unified memory or unknown (no figure invented)\n"
            )),
        }
    }
    OptimizedConfigFile {
        relative_path: ".mgc-optimizer/gpu.env".to_string(),
        content,
        description: match hw.gpu_detection_status {
            crate::commands::optimizer::detect::GpuDetectionStatus::Available => {
                format!("Measured GPU facts ({} GPU(s))", hw.gpus.len())
            }
            crate::commands::optimizer::detect::GpuDetectionStatus::Partial => {
                format!("Partial GPU inventory ({} observed)", hw.gpus.len())
            }
            crate::commands::optimizer::detect::GpuDetectionStatus::Unavailable => {
                "GPU detection unavailable".to_string()
            }
        },
    }
}
