//! Language-specific library scaffold output.
//! Output scaffold thư viện theo ngôn ngữ.

use std::path::Path;

use anyhow::Result;

use crate::scaffold::processors::{slugify, write_file};

pub(in crate::scaffold::processors::lib::implementation) fn write(
    target: &Path,
    name: &str,
) -> Result<()> {
    write_file(
        &target.join("Cargo.toml"),
        &format!(
            "[package]\nname = \"{}\"\nversion = \"0.1.0\"\nedition = \"2024\"\n\n[workspace]\n",
            slugify(name)
        ),
    )?;
    // Seed a deterministic empty dependency lock so `mgc build`
    // can honor Cargo's `--locked --offline` compiler boundary.
    // Tạo lock rỗng ổn định để build giữ nguyên biên `--locked --offline`.
    write_file(
        &target.join("Cargo.lock"),
        &format!(
            concat!(
                "# This file is automatically @generated by Cargo.\n",
                "# It is not intended for manual editing.\n",
                "version = 4\n",
                "\n",
                "[[package]]\n",
                "name = \"{}\"\n",
                "version = \"0.1.0\"\n"
            ),
            slugify(name)
        ),
    )?;
    // cargo test with zero #[test]s exits 0 with "0 tests
    // run" — a pass with zero evidence. Ship a real
    // assertion so `mgc test` (cargo test) proves the
    // scaffold compiles AND behaves.
    // cargo test với 0 #[test] exit 0 với "0 tests run" —
    // pass không bằng chứng. Mang assertion thật để `mgc
    // test` (cargo test) chứng minh template vừa compile
    // vừa chạy đúng.
    write_file(
        &target.join("src").join("lib.rs"),
        concat!(
            "pub fn hello() -> &'static str {\n",
            "    \"hello from MagiCore\"\n",
            "}\n",
            "\n",
            "#[cfg(test)]\n",
            "mod scaffold_tests {\n",
            "    #[test]\n",
            "    fn hello_returns_scaffold_greeting() {\n",
            "        assert_eq!(super::hello(), \"hello from MagiCore\");\n",
            "    }\n",
            "}\n"
        ),
    )?;
    Ok(())
}
