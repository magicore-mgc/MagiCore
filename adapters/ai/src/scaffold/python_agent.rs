//! `python-agent` skeleton: an agent module driven by an LLM client.
//! Skeleton `python-agent`: module agent điều khiển bởi client LLM.
//!
//! The layout follows the stable entry script the AI adapter already routes
//! `mgc dev` through (`src/agent.py`), so a freshly created project runs without
//! any path rewrite.
//! Bố cục theo đúng entry script ổn định mà adapter AI đã định tuyến `mgc
//! dev` (`src/agent.py`), nên project vừa tạo chạy được không cần sửa path.

use mgc_types::MgResult;

use super::layout::ProjectLayout;
use super::slug::module_name;

/// Write the Python-Agent project files (manifest excluded).
/// Ghi file project Python-Agent (không gồm manifest).
pub(super) async fn write(layout: &ProjectLayout) -> MgResult<()> {
    layout.write_package_file("__init__.py", INIT_FILE)?;
    layout.write_package_file("agent.py", AGENT_FILE)?;
    layout.write_package_file("__main__.py", MAIN_FILE)?;
    // The shim imports the package by its real identifier, never by the
    // directory name the project happens to have.
    // (Shim import package bằng identifier thật, không dùng tên thư mục.)
    let entry = ENTRY_SHIM_FILE.replace("{package}", &module_name(layout.package()));
    layout.write("src/agent.py", &entry)?;
    layout.write("README.md", &readme(layout))?;
    layout.write(".gitignore", GITIGNORE_FILE)?;
    Ok(())
}

/// Package docstring plus the public surface the entry points import.
/// Docstring package cùng bề mặt công khai mà entry point import.
const INIT_FILE: &str = r#""""Agent package generated by MagiCore.

Entry points:
    python -m <package>   run the agent loop
    src/agent.py          entry script used by `mgc dev`
"""
"#;

/// The agent loop: one user turn in, one assistant answer out.
/// Vòng agent: một lượt người dùng vào, một câu trả lời ra.
const AGENT_FILE: &str = r#""""Minimal agent loop backed by an OpenAI-compatible chat endpoint.

The endpoint is configurable through the environment so the same code runs
against a hosted API or a local server:
    OPENAI_API_KEY   credential for the endpoint
    OPENAI_BASE_URL  optional override, e.g. http://localhost:PORT/v1
"""

from __future__ import annotations

import os
from dataclasses import dataclass, field

from openai import OpenAI

SYSTEM_PROMPT = (
    "You are a concise assistant. Answer in the language the user writes in."
)


@dataclass
class Agent:
    """Stateful conversation wrapper around a chat-completions client."""

    model: str = field(default_factory=lambda: os.environ.get("AGENT_MODEL", "gpt-4o-mini"))
    client: OpenAI = field(default_factory=OpenAI)
    messages: list[dict[str, str]] = field(
        default_factory=lambda: [{"role": "system", "content": SYSTEM_PROMPT}]
    )

    def ask(self, prompt: str) -> str:
        """Send one user turn and return the assistant text."""
        self.messages.append({"role": "user", "content": prompt})
        completion = self.client.chat.completions.create(
            model=self.model,
            messages=self.messages,
        )
        answer = completion.choices[0].message.content or ""
        self.messages.append({"role": "assistant", "content": answer})
        return answer


def run() -> int:
    """Read prompts from stdin until end of input or `exit`."""
    agent = Agent()
    while True:
        try:
            prompt = input("you> ").strip()
        except EOFError:
            return 0
        if prompt in {"", "exit", "quit"}:
            return 0
        print(f"agent> {agent.ask(prompt)}")
"#;

/// `python -m <package>` entry point — entry point `python -m <package>`.
const MAIN_FILE: &str = r#""""Module entry point for the generated agent."""

from .agent import run

if __name__ == "__main__":
    raise SystemExit(run())
"#;

/// Entry script MagiCore's AI dev runner executes.
/// Entry script mà dev runner AI của MagiCore chạy.
const ENTRY_SHIM_FILE: &str = r#""""Entry script MagiCore runs for `mgc dev`; delegates to the package."""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from {package}.agent import run  # noqa: E402

if __name__ == "__main__":
    raise SystemExit(run())
"#;

/// README describing the generated project and the commands that work offline.
/// README mô tả project sinh ra và các lệnh dùng được offline.
fn readme(layout: &ProjectLayout) -> String {
    format!(
        r#"# {distribution}

A minimal Python agent project generated by MagiCore.

- Core: `ai`
- Framework: `python-agent`
- Package: `{package}` (`src/{package}/`)
- Entry script: `src/agent.py` (the script `mgc dev` runs)

## Layout

```
pyproject.toml      packaging metadata and dependencies
src/agent.py        entry script that delegates to the package
src/{package}/      importable package (agent loop + `__main__`)
```

## Configure

Set the endpoint through the environment before the first run:

```sh
export OPENAI_API_KEY=...                 # credential
export OPENAI_BASE_URL=http://localhost:PORT/v1   # optional override
```

## Next

```sh
mgc install   # resolve dependencies into mgc.lock (no pip/uv spawn)
mgc dev       # run src/agent.py
```
"#,
        distribution = layout.distribution(),
        package = layout.package(),
    )
}

/// Python build/cache artefacts and local secrets never enter a repository.
/// Artifact build/cache Python và secret cục bộ không bao giờ vào repository.
const GITIGNORE_FILE: &str = r#"__pycache__/
*.py[cod]
*.egg-info/
build/
dist/
.venv/
.env
"#;
