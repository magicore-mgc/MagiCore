//! `mcp-server` skeleton: a Model Context Protocol server over stdio.
//! Skeleton `mcp-server`: server Model Context Protocol qua stdio.
//!
//! Transport is the standard MCP stdio shape: one JSON-RPC 2.0 message per
//! newline-delimited line on stdin, responses on stdout, logs on stderr only.
//! The entry file is `server.py` at the project root, matching the stable entry
//! script the AI adapter routes `mgc dev` through.
//! Transport là dạng MCP stdio chuẩn: mỗi dòng stdin là một message JSON-RPC
//! 2.0 phân tách bằng newline, phản hồi ghi stdout, log chỉ ra stderr. Entry
//! file là `server.py` ở gốc project, khớp entry script ổn định của adapter.
//!
//! No MCP SDK is required: the loop below implements the initialize /
//! tools/list / tools/call subset in the standard library so the generated
//! project runs without resolving anything first.
//! Không cần SDK MCP: vòng lặp dưới đây cài tập con initialize / tools/list /
//! tools/call bằng thư viện chuẩn, nên project chạy được ngay không cần cài.

use mgc_types::MgResult;

use super::layout::ProjectLayout;

/// Write the MCP server project files (manifest excluded).
/// Ghi file project server MCP (không gồm manifest).
pub(super) async fn write(layout: &ProjectLayout) -> MgResult<()> {
    layout.write_package_file("__init__.py", INIT_FILE)?;
    layout.write_package_file("tools.py", TOOLS_FILE)?;
    layout.write("server.py", &server_source(layout))?;
    layout.write("README.md", &readme(layout))?;
    layout.write(".gitignore", GITIGNORE_FILE)?;
    Ok(())
}

/// Protocol revision the generated server advertises.
/// Phiên bản protocol mà server sinh ra quảng bá.
pub(super) const PROTOCOL_VERSION: &str = "2024-11-05";

/// Fill the stdio loop template with this project's names and revision.
/// Điền template vòng lặp stdio với tên project và phiên bản protocol.
fn server_source(layout: &ProjectLayout) -> String {
    SERVER_FILE
        .replace("@PROTOCOL@", PROTOCOL_VERSION)
        .replace("@NAME@", layout.distribution())
        .replace("@PACKAGE@", layout.package())
}

/// Package docstring — docstring package.
const INIT_FILE: &str = r#""""MCP server package generated by MagiCore.

`tools.py` holds the tool registry; `server.py` at the project root implements
the stdio JSON-RPC loop that exposes it.
"""
"#;

/// Tool registry: a name, a JSON schema, and a handler.
/// Registry tool: tên, JSON schema và handler.
const TOOLS_FILE: &str = r#""""Tool registry for the generated MCP server.

Add a tool by declaring its schema and handler in `TOOLS`; the server
loop in `server.py` exposes whatever this module lists.
"""

from __future__ import annotations

from typing import Any, Callable


def echo(text: str) -> str:
    """Return the input unchanged; the smallest useful tool."""
    return text


TOOLS: dict[str, dict[str, Any]] = {
    "echo": {
        "description": "Echo the provided text back to the caller.",
        "inputSchema": {
            "type": "object",
            "properties": {"text": {"type": "string"}},
            "required": ["text"],
        },
        "handler": echo,
    },
}


def handler_for(name: str) -> Callable[..., str] | None:
    """Return the handler registered for `name`, if any."""
    entry = TOOLS.get(name)
    if entry is None:
        return None
    return entry["handler"]
"#;

/// Newline-delimited JSON-RPC 2.0 loop on stdin/stdout.
/// Vòng lặp JSON-RPC 2.0 phân tách newline trên stdin/stdout.
///
/// Placeholders are `@PROTOCOL@`, `@NAME@` and `@PACKAGE@`; they are substituted
/// at write time because the Rust format macros cannot coexist with the many
/// Python braces and f-strings in one raw literal.
/// Placeholder là `@PROTOCOL@`, `@NAME@`, `@PACKAGE@` được thay lúc ghi, vì macro
/// format Rust không thể sống chung với quá nhiều ngoặc và f-string Python.
const SERVER_FILE: &str = r#""""Model Context Protocol server over stdio.

Read one JSON-RPC 2.0 message per line from stdin and write one response per
line to stdout. Anything diagnostic goes to stderr so it cannot corrupt the
protocol stream. Run it with `python server.py` or let `mgc dev` start it.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

# Import the package from `src/` without installing it first.
sys.path.insert(0, str(Path(__file__).resolve().parent / "src"))

from @PACKAGE@.tools import TOOLS, handler_for  # noqa: E402

PROTOCOL_VERSION = "@PROTOCOL@"
SERVER_INFO = {"name": "@NAME@", "version": "0.1.0"}


def log(message: str) -> None:
    """Write a diagnostic line; stderr keeps the protocol stream clean."""
    print(message, file=sys.stderr, flush=True)


def ok(request_id: object, result: dict) -> dict:
    return {"jsonrpc": "2.0", "id": request_id, "result": result}


def fail(request_id: object, code: int, message: str) -> dict:
    return {"jsonrpc": "2.0", "id": request_id, "error": {"code": code, "message": message}}


def describe_tools() -> list[dict]:
    """Public tool list without the Python handler references."""
    return [
        {"name": name, "description": entry["description"], "inputSchema": entry["inputSchema"]}
        for name, entry in TOOLS.items()
    ]


def call_tool(params: dict) -> dict:
    name = params.get("name", "")
    arguments = params.get("arguments") or {}
    handler = handler_for(name)
    if handler is None:
        raise LookupError("unknown tool: " + str(name))
    output = handler(**arguments)
    return {"content": [{"type": "text", "text": str(output)}]}


def dispatch(message: dict) -> dict | None:
    """Answer one request; notifications (no id) get no response."""
    method = message.get("method", "")
    request_id = message.get("id")
    if request_id is None:
        return None
    try:
        if method == "initialize":
            return ok(
                request_id,
                {
                    "protocolVersion": PROTOCOL_VERSION,
                    "capabilities": {"tools": {}},
                    "serverInfo": SERVER_INFO,
                },
            )
        if method == "tools/list":
            return ok(request_id, {"tools": describe_tools()})
        if method == "tools/call":
            return ok(request_id, call_tool(message.get("params") or {}))
    except LookupError as error:
        return fail(request_id, -32602, str(error))
    except TypeError as error:
        return fail(request_id, -32602, "invalid arguments: " + str(error))
    return fail(request_id, -32601, "method not found: " + str(method))


def serve() -> int:
    """Run the stdio loop until stdin closes."""
    log(SERVER_INFO["name"] + " MCP server ready on stdio")
    for line in sys.stdin:
        line = line.strip()
        if not line:
            continue
        try:
            message = json.loads(line)
        except json.JSONDecodeError:
            response = fail(None, -32700, "parse error")
        else:
            response = dispatch(message)
        if response is not None:
            sys.stdout.write(json.dumps(response) + "\n")
            sys.stdout.flush()
    return 0


if __name__ == "__main__":
    raise SystemExit(serve())
"#;

/// README describing the server, its tools and how to run it.
/// README mô tả server, các tool và cách chạy.
fn readme(layout: &ProjectLayout) -> String {
    format!(
        r#"# {distribution}

A Model Context Protocol (MCP) server generated by MagiCore.

- Core: `ai`
- Framework: `mcp-server`
- Transport: stdio, one JSON-RPC 2.0 message per line
- Entry script: `server.py` (the script `mgc dev` runs)

## Layout

```
pyproject.toml      packaging metadata and dependencies
server.py           stdio JSON-RPC loop (initialize, tools/list, tools/call)
src/{package}/tools.py   tool registry: schemas and handlers
```

## Add a tool

Declare a schema and a handler entry in `TOOLS` inside
`src/{package}/tools.py`; the loop in `server.py` exposes it immediately.

## Run

```sh
mgc install      # resolve dependencies into mgc.lock
mgc dev          # start server.py on stdio
```

Point an MCP client at the command `mgc dev` (or `python server.py`) in this
directory.
"#,
        distribution = layout.distribution(),
        package = layout.package(),
    )
}

