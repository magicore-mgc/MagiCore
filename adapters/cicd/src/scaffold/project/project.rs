//! Write an offline CI/CD project: pipeline file, README, and `.gitignore`.
//! Ghi project CI/CD offline: file pipeline, README và `.gitignore`.
//!
//! This is the built-in generator behind `mgc create-cicd`. It writes only
//! files — it never spawns a host tool and never needs the registry layer — so
//! a machine with no network still gets a project whose pipeline is the same
//! bytes `mgc ci-generate` produces.
//! Đây là generator có sẵn sau `mgc create-cicd`. Nó chỉ ghi file — không
//! spawn tool nào và không cần registry layer — nên máy không mạng vẫn có
//! project với pipeline đúng bytes `mgc ci-generate` sinh ra.

use std::path::Path;

use mgc_types::MgResult;

use super::super::layout::generation_plan;
use crate::provider::CicdProvider;

/// Write the skeleton for `provider` into `target_dir`.
/// Ghi skeleton cho `provider` vào `target_dir`.
///
/// The destination must not exist yet: a create never merges into an existing
/// tree, and the caller reports the same conflict on its other source paths.
/// Đích chưa được tồn tại: create không hòa vào cây đã có, và caller báo cùng
/// lỗi xung đột ở các đường nguồn khác.
pub async fn scaffold_project(
    provider: CicdProvider,
    project_name: &str,
    target_dir: &Path,
) -> MgResult<()> {
    if target_dir.try_exists()? {
        return Err(mgc_types::MgError::Unsupported {
            core: "cicd",
            capability: "scaffold",
            guidance: format!("Directory '{}' already exists", target_dir.display()),
        });
    }
    std::fs::create_dir_all(target_dir)?;

    for file in generation_plan(provider, project_name)? {
        let path = target_dir.join(&file.relative_path);
        if file.create_parent
            && let Some(parent) = path.parent()
        {
            std::fs::create_dir_all(parent)?;
        }
        write_regular_file(&path, &file.contents)?;
    }
    write_regular_file(
        &target_dir.join("README.md"),
        &readme(provider, project_name),
    )?;
    write_regular_file(&target_dir.join(".gitignore"), GITIGNORE)?;
    Ok(())
}

/// Readme contents: what the project is and how to regenerate its pipeline.
/// Nội dung README: project là gì và cách sinh lại pipeline.
fn readme(provider: CicdProvider, project_name: &str) -> String {
    let pipeline = generation_plan(provider, project_name)
        .map(|files| {
            files
                .into_iter()
                .map(|file| file.relative_path.display().to_string())
                .collect::<Vec<_>>()
                .join(", ")
        })
        .unwrap_or_default();
    format!(
        "# {project_name}\n\
         \n\
         CI/CD project generated by MagiCore for the **{provider}** provider.\n\
         \n\
         - Pipeline: `{pipeline}` (generated by `mgc ci-generate`; regenerate instead of editing by hand).\n\
         - Validate the pipeline and project: `mgc verify`.\n\
         - Regenerate after config changes: `mgc ci-generate`.\n\
         - Deployment is provider-specific and stays unavailable until a native provider engine ships.\n",
        provider = provider.as_str(),
    )
}

/// Files MagiCore-owned tooling writes that must never be committed.
/// File do tooling MagiCore ghi mà không được commit.
const GITIGNORE: &str = "# MagiCore local state — trạng thái cục bộ của MagiCore\n\
.magicore/\n\
mgc.lock\n";

/// Write one regular file, creating parents and refusing a symlink destination.
/// Ghi một file thường, tạo thư mục cha và từ chối đích là symlink.
fn write_regular_file(path: &Path, contents: &str) -> MgResult<()> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    // A pre-existing symlink would redirect the write outside the project tree.
    // (Symlink sẵn có sẽ chuyển hướng ghi ra ngoài cây project.)
    if std::fs::symlink_metadata(path)
        .map(|metadata| metadata.file_type().is_symlink())
        .unwrap_or(false)
    {
        return Err(mgc_types::MgError::Unsupported {
            core: "cicd",
            capability: "scaffold",
            guidance: format!(
                "refusing to write scaffold file '{}': destination is a symlink",
                path.display()
            ),
        });
    }
    std::fs::write(path, contents)?;
    Ok(())
}
